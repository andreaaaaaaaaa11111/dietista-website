-- Schema applicativo Supabase/PostgreSQL per il sito della Dietista Arianna Pelliccioni.
-- Le regole RLS consentono gli invii pubblici, ma riservano lettura e gestione all'admin.

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text,
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.services (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  duration integer not null check (duration > 0),
  price integer not null check (price >= 0),
  active boolean not null default true,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.consultation_requests (
  id bigint generated by default as identity primary key,
  user_uid uuid references auth.users(id) on delete set null,
  service_id bigint references public.services(id) on delete set null,
  name text not null,
  email text not null,
  phone text,
  age integer,
  weight numeric(6,2),
  height numeric(6,2),
  goal text,
  medical_conditions text,
  allergies text,
  current_diet text,
  message text,
  privacy_consent boolean not null default false,
  privacy_consent_date timestamptz,
  status text not null default 'new' check (status in ('pending_verification', 'new', 'contacted', 'scheduled', 'completed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.contact_requests (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text,
  consultation_type text,
  message text not null,
  status text not null default 'new' check (status in ('new', 'read', 'replied')),
  created_at timestamptz not null default now()
);

create table public.testimonials (
  id bigint generated by default as identity primary key,
  user_uid uuid references auth.users(id) on delete set null,
  name text not null,
  email text,
  content text not null,
  rating integer not null check (rating between 1 and 5),
  image_url text,
  approved boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.site_events (
  id bigint generated by default as identity primary key,
  user_uid uuid references auth.users(id) on delete set null,
  event_type text not null check (event_type in ('page_view', 'booking_submitted', 'contact_submitted')),
  path text not null,
  service_id bigint references public.services(id) on delete set null,
  created_at timestamptz not null default now()
);

create index consultation_requests_created_at_idx on public.consultation_requests(created_at desc);
create index consultation_requests_status_idx on public.consultation_requests(status);
create index consultation_requests_email_idx on public.consultation_requests(lower(email));
create index contact_requests_created_at_idx on public.contact_requests(created_at desc);
create index testimonials_created_at_idx on public.testimonials(created_at desc);
create index site_events_created_at_idx on public.site_events(created_at desc);
create index site_events_type_idx on public.site_events(event_type);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger services_set_updated_at
before update on public.services
for each row execute function public.set_updated_at();

create trigger consultation_requests_set_updated_at
before update on public.consultation_requests
for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email, full_name, role)
  values (
    new.id,
    coalesce(new.email, ''),
    case
      when lower(coalesce(new.email, '')) in ('andreapelliccioni12@gmail.com', 'pelliccioniarianna.dietista@gmail.com')
        then 'Arianna Pelliccioni'
      else coalesce(new.raw_user_meta_data ->> 'name', split_part(coalesce(new.email, 'Utente'), '@', 1))
    end,
    case
      when lower(coalesce(new.email, '')) in ('andreapelliccioni12@gmail.com', 'pelliccioniarianna.dietista@gmail.com')
        then 'admin'
      else 'user'
    end
  )
  on conflict (id) do update
  set email = excluded.email,
      full_name = excluded.full_name,
      role = case when excluded.role = 'admin' then 'admin' else public.profiles.role end,
      updated_at = now();
  return new;
end;
$$;

create trigger on_auth_user_created
after insert or update of email, raw_user_meta_data on auth.users
for each row execute function public.handle_new_user();

